import { test, expect } from '@playwright/test'

test('Floyd tables, variant players, history and negative cycle feedback', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/Animate/floyd/')
  await expect(page.getByText('初始化：对角线', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: '跳到下一个 k' }).click()
  await expect(page.locator('.calculation')).toContainText('k = 1')
  await expect(page.locator('.animation-controls')).toContainText('1/250')
  await page.getByRole('button', { name: '二维 DP · 原地更新' }).click()
  await expect(page.locator('.animation-controls')).toContainText('0/250')
  await page.getByRole('button', { name: '下一帧', exact: true }).click()
  await expect(page.locator('.calculation')).toContainText('比较')
  await page.getByRole('button', { name: '下一帧', exact: true }).click()
  await expect(page.locator('.calculation')).toContainText('更新结果')
  await page.getByRole('button', { name: '三维 DP · 分层' }).click()
  await expect(page.locator('.animation-controls')).toContainText('1/250')
  await page.getByRole('spinbutton', { name: '跳转到帧' }).fill('250')
  await page.getByRole('button', { name: '确认跳转' }).click()
  await expect(page.getByText('计算完成：表格为所有点对的最短距离。')).toBeVisible()
  await page.getByRole('combobox', { name: '历史 DP 层' }).selectOption('5')
  await expect(page.getByText('历史层 · k = 5', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: '选择图数据' }).selectOption('3')
  await expect(page.getByRole('alert')).toContainText('负环')
  await expect(page.getByRole('button', { name: '播放', exact: true })).toBeDisabled()
  expect(errors).toEqual([])
})

