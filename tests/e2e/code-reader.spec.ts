import { expect, test } from '@playwright/test'

test('reading controls persist across algorithms and keep the execution line visible', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/Animate/bfs/')
  await expect(page.locator('.ace_editor')).toHaveCSS('font-size', '15px')
  await page.getByRole('button', { name: '下一帧', exact: true }).click()
  const enlarge = page.getByRole('button', { name: '增大代码字号' })
  // Space activates the focused button without triggering the global playback shortcut.
  await enlarge.focus()
  await page.keyboard.press('Space')
  await expect(page.locator('.ace_editor')).toHaveCSS('font-size', '16px')
  await expect(page.getByRole('button', { name: '播放', exact: true })).toBeVisible()
  await expect(page.locator('.execution-gutter').first()).toBeInViewport()
  await expect(page.locator('.highlightLine').first()).toBeInViewport()
  await page.getByRole('button', { name: '自动换行' }).click()
  await page.reload()
  await expect(page.locator('.ace_editor')).toHaveCSS('font-size', '16px')
  await expect(page.getByRole('button', { name: '自动换行' })).toHaveAttribute('aria-pressed', 'true')
  await page.goto('/Animate/floyd/')
  await expect(page.locator('.ace_editor')).toHaveCSS('font-size', '16px')
  await page.getByRole('button', { name: '二维 DP · 原地更新' }).click()
  await expect(page.locator('.ace_editor')).toHaveCSS('font-size', '16px')
  await page.getByRole('button', { name: '重置代码字号' }).click()
  await expect(page.locator('.ace_editor')).toHaveCSS('font-size', '15px')
  await expect(page.getByRole('button', { name: '自动换行' })).toHaveAttribute('aria-pressed', 'true')
})

test('font limits and wrapped code work on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/Animate/floyd/')
  await page.getByRole('tab', { name: '代码', exact: true }).click()
  const smaller = page.getByRole('button', { name: '减小代码字号' })
  for (let i = 0; i < 3; i++) await smaller.click()
  await expect(smaller).toBeDisabled()
  await expect(page.locator('.ace_editor')).toHaveCSS('font-size', '12px')
  const larger = page.getByRole('button', { name: '增大代码字号' })
  for (let i = 0; i < 12; i++) await larger.click()
  await expect(larger).toBeDisabled()
  await expect(page.locator('.ace_editor')).toHaveCSS('font-size', '24px')
  const before = await page.locator('.ace_line_group').count()
  await page.getByRole('button', { name: '自动换行' }).click()
  await expect(page.locator('.ace_line_group').first()).toBeVisible()
  // Wrapped logical lines render as groups containing multiple screen lines.
  expect(await page.locator('.ace_line_group').count()).toBeGreaterThan(before)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await expect(page.locator('.code-toolbar')).toBeInViewport()
  await page.getByRole('tab', { name: '状态', exact: true }).click()
  await page.getByRole('tab', { name: '代码', exact: true }).click()
  await expect(page.locator('.ace_editor')).toHaveCSS('font-size', '24px')
})

test('unavailable saved settings do not prevent the code panel from loading', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(Storage.prototype, 'getItem', { value() { throw new Error('Storage unavailable') } })
    Object.defineProperty(Storage.prototype, 'setItem', { value() { throw new Error('Storage unavailable') } })
  })
  await page.goto('/Animate/bfs/')
  await expect(page.locator('.ace_editor')).toHaveCSS('font-size', '15px')
  await page.getByRole('button', { name: '增大代码字号' }).click()
  await expect(page.locator('.ace_editor')).toHaveCSS('font-size', '16px')
})
